const dict: Record<Lang, Record<Key, string>> = { ru, en };

type TFn = (k: Key, vars?: Record<string, string | number>) => string;
const I18nCtx = createContext<{ t: TFn; lang: Lang }>(null as unknown as { t: TFn; lang: Lang });

export function I18nProvider({ children }: { children: ReactNode }) {
  const { prefs } = usePrefs();
  const lang = prefs.lang;
  const t = useCallback<TFn>(
    (k, vars) => {
      let s = dict[lang][k] ?? dict.ru[k] ?? k;
      if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, String(v));
      return s;
    },
    [lang],
  );
  return <I18nCtx.Provider value={{ t, lang }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
